function T = gui_theme()
%GUI_THEME  实验3 展示 GUI 的全局配色 / 字号规范 (浅色专业风)
%
%   用法:   T = gui_theme();
%   设计意图: 所有 Tab 统一从这里取色 —— 将来换肤只改这一个文件。
%
%   颜色均为 0~1 的 [r g b]:
%     bg        窗口底色 (浅灰蓝)
%     card      卡片 / 面板底色 (纯白)
%     text      主文字 (近黑)
%     textSub   次要文字 (中灰)
%     head      标题文字 (深蓝灰)
%     primary   主色 (蓝)      ok/warn/bad  状态色 (绿/橙/红)
%     line      分割线 (浅灰)

    T = struct( ...
        'bg',      [0.957 0.965 0.980], ...
        'card',    [1.000 1.000 1.000], ...
        'text',    [0.122 0.141 0.188], ...
        'textSub', [0.420 0.447 0.502], ...
        'head',    [0.176 0.208 0.290], ...
        'primary', [0.176 0.357 1.000], ...
        'ok',      [0.071 0.631 0.314], ...
        'warn',    [0.910 0.529 0.118], ...
        'bad',     [0.851 0.247 0.247], ...
        'line',    [0.886 0.902 0.933], ...
        'fsBig', 22, 'fsTitle', 15, 'fsHead', 13, 'fsBody', 11, 'fsSmall', 10);
end